# ИЗМЕНЕНО 1: В функцию page.goto() добавлен аргумент wait_until="domcontentloaded".
#  Зачем: Исходный код просто открывал страницу, что могло привести к ошибкам таймаута на медленном интернете, пока грузятся все скрипты и картинки.
# ИЗМЕНЕННО 2:Удалена строка self.page.locator("#foobar").click().
#  Зачем: В документации приведен абстрактный пример. На реальном сайте Microsoft нет элемента с id="foobar", поэтому тест упал бы.
# ИЗМЕНЕННО 3: добавленна проверка self.assertIn("Microsoft", page_title).
# Зачем: Чтобы тест имел практический смысл, мы извлекаем заголовок страницы и проверяем , что открылся именно нужный сайт, а не страница с ошибеой 404
class MyTest(unittest.TestCase):
    
    # Фикстура autouse=True автоматически передает объект Page в тесты.
    # Это позволяет нам не прописывать запуск браузера вручную в каждом тесте.
    @pytest.fixture(autouse=True)
    def setup(self, page: Page):
        self.page = page

    def test_microsoft_title(self):
        # ИЗМЕНЕННО 1: Добавил параметр wait_until="domcontentloaded".
        # Зачем: Чтобы тест был стабильнее и не падал, дожидаясь загрузки тяжелых картинок.
        self.page.goto("https://microsoft.com", wait_until="domcontentloaded")
        
        # 2. Исходный код из документации:
        # self.page.locator("#foobar").click()
        
        # ИЗМЕНЕННО 2: я убрала поиск несуществующего элемента #foobar.
        # Зачем: На реальном сайте Microsoft нет кнопки с таким ID, тест бы упал.
        # Вместо этого мы проверяем заголовок страницы, что является базовым тестом.
        page_title = self.page.title()
        
        # 3. Исходный код из документации:
        # assert self.page.evaluate("1 + 1") == 2
        
        # ИЗМЕНЕННО 3: я заменила  проверку математики на проверку того, 
        # что мы действительно находимся на сайте Microsoft.
        self.assertIn("Microsoft", page_title, "Заголовок страницы не содержит слово Microsoft")
        
        # Оставляю проверку математики из документации для демонстрации evaluate()
        assert self.page.evaluate("1 + 1") == 2

if __name__ == '__main__':
    unittest.main()
    # Эта конструкция нужна для того, чтобы запускать тесты,
    # когда файл запускается сам по себе, и предотвращать их случайный запуск, если файл импортируется в другой код.